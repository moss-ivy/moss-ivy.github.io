class I18nManager {
  constructor() {
    this.currentLang = this.getInitialLang();
    this.init();
  }

  getInitialLang() {
    // 1. Zkontroluj parametr URL (?lang=cs nebo ?lang=en)
    const urlParams = new URLSearchParams(window.location.search);
    const paramLang = urlParams.get('lang');
    if (paramLang && (paramLang === 'cs' || paramLang === 'en')) {
      return paramLang;
    }
    // 2. Zkontroluj uloženou volbu v localStorage
    const saved = localStorage.getItem('site_lang');
    if (saved && (saved === 'cs' || saved === 'en')) {
      return saved;
    }
    // 3. Výchozí je angličtina dle zadání
    return 'en';
  }

  init() {
    this.applyLanguage(this.currentLang);
    this.bindEvents();
  }

  bindEvents() {
    document.querySelectorAll('.lang-btn').forEach(btn => {
      btn.addEventListener('click', (e) => {
        const lang = e.currentTarget.getAttribute('data-lang');
        if (lang && lang !== this.currentLang) {
          this.setLanguage(lang);
        }
      });
    });
  }

  setLanguage(lang) {
    if (!translations[lang]) return;
    this.currentLang = lang;
    localStorage.setItem('site_lang', lang);
    this.applyLanguage(lang);

    // Aktualizace aktivních tlačítek
    document.querySelectorAll('.lang-btn').forEach(btn => {
      btn.classList.toggle('active', btn.getAttribute('data-lang') === lang);
    });

    // Vyvolání události pro případné další skripty
    window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang } }));
  }

  applyLanguage(lang) {
    const dict = translations[lang] || translations.en;
    document.documentElement.lang = lang === 'cs' ? 'cs' : 'en';

    // Aktualizace textových uzlů s atributem data-i18n
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (dict[key]) {
        el.textContent = dict[key];
      }
    });

    // Aktualizace atributů (placeholder, title, aria-label)
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      if (dict[key]) {
        el.setAttribute('placeholder', dict[key]);
      }
    });

    // Aktualizace aktivního stavu tlačítek
    document.querySelectorAll('.lang-btn').forEach(btn => {
      btn.classList.toggle('active', btn.getAttribute('data-lang') === lang);
    });
  }

  t(key) {
    const dict = translations[this.currentLang] || translations.en;
    return dict[key] || key;
  }
}

// Inicializace po načtení DOMu
document.addEventListener('DOMContentLoaded', () => {
  window.i18n = new I18nManager();
});
